"""SCREAM-361 (PO, November 16): residents' cars in Elm Park drawn with the cars from LimeZu Modern
Exteriors (Vehicles, Car 1 to 26), "30% smaller" than the pack's size, with "as much variety in the
cars as possible" (all 26 are used).

Usage (run from the repo root):
    python3 tools/cars/build_cars.py <Modern_Exteriors_Complete_Singles_48x48.zip>

The zip is in the private art repo (icemachine-art). Writes:
    public/assets/limezu/cars.png    one picture sheet: each car's four views (right, down, left, up)
    public/assets/limezu/cars.json   the sheet's frames, for Phaser's atlas loader
    src/config/carModels.ts          each car's size in each view (the truck bumps into exactly that)

Each car is shrunk by CAR_SCALE with nearest-neighbour (as in the mock-up the PO approved), so a
car 183 px long in the pack is 66 px on the map; longer cars stay longer.
"""
import io, json, math, os, re, sys, zipfile
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
OUT_PNG = os.path.join(ROOT, 'public', 'assets', 'limezu', 'cars.png')
OUT_JSON = os.path.join(ROOT, 'public', 'assets', 'limezu', 'cars.json')
OUT_TS = os.path.join(ROOT, 'src', 'config', 'carModels.ts')

# The pack's own size, 30% smaller (PO): its shortest car, 183 px long, becomes 66 px (about 64% of the truck's 104).
CAR_SCALE = 66 / 183
VIEWS = ['right', 'down', 'left', 'up']
PAD = 2


def main(zip_path):
    z = zipfile.ZipFile(zip_path)
    found = {}
    for name in z.namelist():
        m = re.search(r'Vehicles_48x48_Car_(Right|Down|Left|Up)_(\d+)\.png$', name)
        if m:
            found[(int(m.group(2)), m.group(1).lower())] = name
    models = sorted({n for n, _ in found})
    if not models:
        sys.exit('No Vehicles_48x48_Car_* pictures in that zip')
    pics = {}
    for n in models:
        for v in VIEWS:
            im = Image.open(io.BytesIO(z.read(found[(n, v)]))).convert('RGBA')
            im = im.crop(im.getbbox())
            w, h = max(1, round(im.width * CAR_SCALE)), max(1, round(im.height * CAR_SCALE))
            pics[(n, v)] = im.resize((w, h), Image.NEAREST)
    cell_w = max(p.width for p in pics.values()) + PAD
    cell_h = max(p.height for p in pics.values()) + PAD
    sheet = Image.new('RGBA', (cell_w * len(VIEWS), cell_h * len(models)))
    frames, sizes = {}, []
    for row, n in enumerate(models):
        entry = {'model': n}
        for col, v in enumerate(VIEWS):
            p = pics[(n, v)]
            x, y = col * cell_w, row * cell_h
            sheet.alpha_composite(p, (x, y))
            frames[f'car{n}_{v}'] = {'frame': {'x': x, 'y': y, 'w': p.width, 'h': p.height}, 'rotated': False, 'trimmed': False,
                                     'spriteSourceSize': {'x': 0, 'y': 0, 'w': p.width, 'h': p.height},
                                     'sourceSize': {'w': p.width, 'h': p.height}}
            entry[v] = [p.width, p.height]
        sizes.append(entry)
    sheet.save(OUT_PNG)
    json.dump({'frames': frames, 'meta': {'image': 'cars.png', 'size': {'w': sheet.width, 'h': sheet.height}, 'scale': '1'}},
              open(OUT_JSON, 'w'), separators=(',', ':'))
    ts = ['// GENERATED by tools/cars/build_cars.py from LimeZu Modern Exteriors (limezu.itch.io): rerun it, don\'t edit this file.',
          '// SCREAM-361: each car\'s size in each view, px on the map ([width, height] of its picture).',
          '',
          'export interface CarModel {',
          '  model: number;',
          '  right: [number, number];',
          '  down: [number, number];',
          '  left: [number, number];',
          '  up: [number, number];',
          '}',
          '',
          f'export const CAR_MODELS: CarModel[] = {json.dumps(sizes, separators=(",", ":"))};',
          '']
    open(OUT_TS, 'w').write('\n'.join(ts))
    print(f'{len(models)} cars, {sheet.width} x {sheet.height} -> {os.path.relpath(OUT_PNG, ROOT)}, {os.path.relpath(OUT_TS, ROOT)}')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
