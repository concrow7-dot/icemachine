"""Builds the customers' schedule lines (SCREAM-247) from tools/schedule/schedule_lines.csv,
and the neighbours' lines (SCREAM-248) from tools/schedule/neighbour_lines.csv.

Usage (from the repo root):
    python3 tools/schedule/build_schedule_lines.py      # -> src/config/scheduleLines.ts and neighbourLines.ts

schedule_lines.csv is a copy of the "Schedule lines" tab of the PO's Residents sheet (Drive
folder Customers): edit the sheet, then "sync schedule lines". Columns:
    ID, Who (Any, Adult or Kid), Line, Notes
A line says something true about the customer's own week, with at most one kind of tag:
    [Next]  the next day they're home              "See you [Next]!"
    [Back]  the same, but only when they're away tomorrow   "I have soccer until [Back]."
    [Home]  the days they're home (3 at most)      "The best days to visit are [Home]."
    [Away]  the days they're out (3 at most)       "Nobody is home on [Away]."
    no tag  for people who are home all seven days "I'm out here every day."

neighbour_lines.csv is a copy of the "Neighbour lines" tab ("sync neighbour lines"): what a
customer says about someone else on their street. Same columns and tags, but the tags are
about the neighbour, Who is the neighbour's age, and every line must name them with [Name]
([Street] is optional). Keep reasons out of these lines ("has soccer"): the neighbour gives
their own reason, and the two could disagree.
"""
import csv, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
WHO = {'any', 'adult', 'kid'}
# The longest each tag can become, to check the line still fits the speech bubble.
LONGEST = {'[Next]': 'Wednesday', '[Back]': 'Wednesday', '[Home]': 'Wednesday, Thursday and Saturday',
           '[Away]': 'Wednesday, Thursday and Saturday'}
MAX_CHARS = 90


def build(csv_name, out_name, const, type_name, neighbours):
    csv_path = os.path.join(HERE, csv_name)
    out_ts = os.path.join(ROOT, 'src', 'config', out_name)
    allowed = set(LONGEST) | ({'[Name]', '[Street]'} if neighbours else set())
    out, seen = [], set()
    for n, r in enumerate(csv.DictReader(open(csv_path, newline='', encoding='utf-8')), start=2):
        def bad(msg):
            sys.exit(f'{csv_name} row {n} ({r.get("ID")}): {msg}')
        rid = (r['ID'] or '').strip()
        line = ' '.join((r['Line'] or '').split())
        if not rid and not line:
            continue
        if not rid or not line:
            bad('a line needs both an ID and a Line')
        if rid in seen:
            bad('the same ID twice')
        seen.add(rid)
        who = (r['Who'] or '').strip().lower()
        if who not in WHO:
            bad('Who must be Any, Adult or Kid')
        tags = set(re.findall(r'\[[^\]]*\]', line))
        if tags - allowed:
            bad('only ' + ', '.join(sorted(allowed)) + ' can go in square brackets')
        if len(tags & set(LONGEST)) > 1:
            bad('a line can use only one kind of day tag')
        if neighbours and '[Name]' not in line:
            bad('the line must say [Name]')
        longest = line
        for tag, text in LONGEST.items():
            longest = longest.replace(tag, text)
        if len(longest) > MAX_CHARS:
            bad(f'the line can reach {len(longest)} characters; {MAX_CHARS} at most, so it fits the speech bubble')
        out.append({'id': rid, 'who': who, 'text': line})
    ts = [f'// GENERATED by tools/schedule/build_schedule_lines.py from tools/schedule/{csv_name}',
          "// (a copy of a tab of the PO's Residents sheet): edit the sheet, not this file.",
          '',
          "import type { ScheduleLine } from '../state/ScheduleLines';",
          '',
          f'export const {const}: ScheduleLine[] = ' + json.dumps(out, indent=1, ensure_ascii=False) + ';', '']
    open(out_ts, 'w', encoding='utf-8').write('\n'.join(ts))
    print(f'{len(out)} lines -> {out_ts}')


def main():
    build('schedule_lines.csv', 'scheduleLines.ts', 'SCHEDULE_LINES', 'ScheduleLine', False)
    build('neighbour_lines.csv', 'neighbourLines.ts', 'NEIGHBOUR_LINES', 'ScheduleLine', True)


if __name__ == '__main__':
    main()
