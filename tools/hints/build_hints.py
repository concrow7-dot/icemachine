"""Builds the customers' hint lines (SCREAM-103) from tools/hints/hint_lines.csv.

Usage (from the repo root):
    python3 tools/hints/build_hints.py      # -> src/config/hintLines.ts

hint_lines.csv is a copy of the "Hint lines" tab of the PO's Tutorial residents sheet
(doc 23): edit the sheet, then "sync hint lines". Columns:
    ID, Tone (Average, Funny, Dark or Absurd), Who (Any, Adult or Kid), Line, Notes
A line names the regular with [Name] and their street with [Street]. Each regular the
residents sheet marks "Hinted" gets one line for a whole Story run (PO, November 8: a
customer is never hinted at in two different ways in the same story).
"""
import csv, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
CSV_PATH = os.path.join(HERE, 'hint_lines.csv')
OUT_TS = os.path.join(ROOT, 'src', 'config', 'hintLines.ts')
TONES = {'average', 'funny', 'dark', 'absurd'}
WHO = {'any', 'adult', 'kid'}
MAX_CHARS = 90


def main():
    out, seen = [], set()
    for n, r in enumerate(csv.DictReader(open(CSV_PATH, newline='', encoding='utf-8')), start=2):
        def bad(msg):
            sys.exit(f'hint_lines.csv row {n} ({r.get("ID")}): {msg}')
        rid = (r['ID'] or '').strip()
        line = ' '.join((r['Line'] or '').split())
        if not rid and not line:
            continue
        if rid in seen:
            bad('the same ID twice')
        seen.add(rid)
        tone, who = (r['Tone'] or '').strip().lower(), (r['Who'] or '').strip().lower()
        if tone not in TONES:
            bad('Tone must be Average, Funny, Dark or Absurd')
        if who not in WHO:
            bad('Who must be Any, Adult or Kid')
        if '[Name]' not in line:
            bad('the line must say [Name]')
        if set(re.findall(r'\[[^\]]*\]', line)) - {'[Name]', '[Street]'}:
            bad('only [Name] and [Street] can go in square brackets')
        if len(line) > MAX_CHARS:
            bad(f'the line is {len(line)} characters; {MAX_CHARS} at most, so it fits the speech bubble')
        out.append({'id': rid, 'tone': tone, 'who': who, 'text': line})
    ts = ['// GENERATED by tools/hints/build_hints.py from tools/hints/hint_lines.csv',
          '// (a copy of the "Hint lines" tab of the PO\'s Tutorial residents sheet, doc 23): edit the sheet, not this file.',
          '',
          "import type { HintLine } from '../state/Hints';",
          '',
          'export const HINT_LINES: HintLine[] = ' + json.dumps(out, indent=1, ensure_ascii=False) + ';', '']
    open(OUT_TS, 'w', encoding='utf-8').write('\n'.join(ts))
    print(f'{len(out)} hint lines -> {OUT_TS}')


if __name__ == '__main__':
    main()
